import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath:'/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const p = await b.newPage({viewport:{width:1440,height:900}});
await p.goto('http://localhost:4180/home/', {waitUntil:'domcontentloaded'});
await p.waitForTimeout(5000);
console.log('docH', await p.evaluate(()=>document.documentElement.scrollHeight), 'scrollBehavior', await p.evaluate(()=>getComputedStyle(document.documentElement).scrollBehavior));
const target = await p.evaluate(() => { const s=document.getElementById('collections3d').getBoundingClientRect(); return s.top+scrollY+s.height-innerHeight; });
console.log('target', target);
await p.evaluate((y)=>window.scrollTo({top:y,behavior:'instant'}), target);
await p.waitForTimeout(6000);
console.log('scrollY', await p.evaluate(()=>window.scrollY));
console.log(JSON.stringify(await p.evaluate(()=>{const s=window.__sets;return{world:s.worldMap.group.visible,mailer:s.mailer.group.visible,boxes:s.boxes.group.visible};})));
await p.screenshot({path:'/tmp/g_world_settled.png'});
await b.close();
